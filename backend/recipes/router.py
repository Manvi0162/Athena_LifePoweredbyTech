import json
from urllib.parse import quote_plus

from fastapi import APIRouter, Depends, HTTPException
from postgrest.exceptions import APIError
from pydantic import BaseModel, Field

from core.auth import HouseholdContext, get_household_context
from core.errors import db_error
from core.llm import LLMUnavailable

from .generate import generate_recipe
from .matching import canonical, evaluate_recipe, match_recipes

router = APIRouter(prefix="/recipes", tags=["recipes"])

RECIPE_FIELDS = ("id,name,cuisine,description,servings,source_type,verification_status,"
                 "source_url,youtube_url,prep_minutes,cook_minutes,instructions,"
                 "lb_recipe_ingredients(ingredient_name,quantity,unit,optional)")


# Same queries as load_pantry() / load_recipes() in the notebook.
def load_pantry(ctx: HouseholdContext):
    return (ctx.db.table("pantry_items")
            .select("ingredient_name,quantity,unit,available")
            .eq("household_id", ctx.household_id)
            .eq("available", True).gt("quantity", 0).execute().data or [])


def load_recipes(ctx: HouseholdContext):
    return ctx.db.table("lb_recipes").select(RECIPE_FIELDS).execute().data or []


def youtube_link(recipe):
    """Notebook cell 6: stored video if present, otherwise search results."""
    url = recipe.get("youtube_url")
    return {
        "url": url or ("https://www.youtube.com/results?search_query="
                       + quote_plus(recipe["name"] + " recette mauricienne")),
        "type": "stored video" if url else "search results",
    }


class SearchBody(BaseModel):
    ingredients: list[str] = Field(min_length=1, max_length=20)


class RecommendBody(BaseModel):
    servings: int = Field(default=4, ge=1, le=30)
    allergies: list[str] = Field(default_factory=list)
    diet: str = "none"


class DraftBody(BaseModel):
    recipe: dict


class CookBody(BaseModel):
    # Generated by the app once per "I cooked this" tap. Sending it again
    # never deducts twice.
    operation_id: str = Field(pattern=r"^[0-9a-fA-F-]{36}$")


@router.get("")
def list_recipes(ctx: HouseholdContext = Depends(get_household_context)):
    return {"recipes": load_recipes(ctx)}


@router.post("/search")
def search_by_ingredients(body: SearchBody, ctx: HouseholdContext = Depends(get_household_context)):
    """Food photo -> recipes. Send the ingredient names the user confirmed
    after /food/recognize. Read-only."""
    wanted = list(dict.fromkeys(i.strip().lower() for i in body.ingredients if i.strip()))
    if not wanted:
        raise HTTPException(422, detail={"code": "invalid_input", "message": "Give at least one ingredient."})
    recipes = load_recipes(ctx)
    pantry_names = {canonical(p["ingredient_name"]) for p in load_pantry(ctx)}
    matches = match_recipes(recipes, wanted, pantry_names)
    return {
        "searched": len(recipes),
        "ingredients": wanted,
        "matches": [{
            "recipe_id": m["recipe"]["id"],
            "name": m["recipe"]["name"],
            "verification_status": m["recipe"].get("verification_status"),
            "uses_from_photo": m["matched"],
            "already_in_pantry": m["in_pantry"],
            "still_to_buy": m["to_buy"],
            "youtube": youtube_link(m["recipe"]),
        } for m in matches[:10]],
        "note": "Allergy/diet safety requires user review.",
    }


@router.post("/recommend")
def recommend(body: RecommendBody, ctx: HouseholdContext = Depends(get_household_context)):
    """Notebook cell 5: a verified recipe that can be cooked now, otherwise an
    AI draft (not saved; save it with /recipes/drafts)."""
    pantry = load_pantry(ctx)
    ranked = sorted((evaluate_recipe(r, pantry) for r in load_recipes(ctx)),
                    key=lambda x: (x["cook_now"], x["coverage"]), reverse=True)
    verified = [r for r in ranked if r["cook_now"]
                and r["recipe"].get("verification_status") == "verified"]
    if verified:
        recommendation, source = verified[0]["recipe"], "verified_database"
    else:
        try:
            recommendation = generate_recipe(pantry, servings=body.servings,
                                             allergies=body.allergies, diet=body.diet)
        except ValueError as exc:
            raise HTTPException(422, detail={"code": "cannot_generate", "message": str(exc)})
        except (LLMUnavailable, json.JSONDecodeError):
            raise HTTPException(503, detail={"code": "ai_unavailable",
                                             "message": "Recipe suggestions are unavailable. Try again shortly."})
        source = "ai_generated"
    assessment = evaluate_recipe(recommendation, pantry)
    return {
        "source": source,
        "recipe": recommendation,
        "coverage": assessment["coverage"],
        "missing": assessment["missing"],
        "quantities_to_review": assessment["uncertain"],
        "cook_now": assessment["cook_now"],
        "youtube": youtube_link(recommendation),
        "note": "Allergy/diet safety requires user review.",
    }


@router.post("/drafts")
def save_draft(body: DraftBody, ctx: HouseholdContext = Depends(get_household_context)):
    """Notebook cell 7: save an AI recipe as a private pending draft."""
    try:
        recipe_id = ctx.db.rpc("lb_save_ai_recipe", {
            "p_household_id": ctx.household_id, "p_recipe": body.recipe}).execute().data
    except APIError as exc:
        raise db_error(exc)
    return {"recipe_id": recipe_id, "verification_status": "pending"}


@router.post("/{recipe_id}/cook")
def cook(recipe_id: str, body: CookBody, ctx: HouseholdContext = Depends(get_household_context)):
    """Confirm cooking: deducts each tracked ingredient once (lb_confirm_cooking v2).
    Water and ingredients not in the pantry are skipped and listed."""
    try:
        return ctx.db.rpc("lb_confirm_cooking", {
            "p_household_id": ctx.household_id,
            "p_recipe_id": recipe_id,
            "p_operation_id": body.operation_id,
        }).execute().data
    except APIError as exc:
        raise db_error(exc)
