def collect_domain_recommendations(
    food_results=None,
    water_results=None,
    electricity_results=None
):
    modules = {
        "food": food_results or [],
        "water": water_results or [],
        "electricity": electricity_results or []
    }

    combined = []
    seen_ids = set()

    for module, recommendations in modules.items():

        for rec in recommendations:
            validate_domain_recommendation(rec)

            if rec["module"] != module:
                raise ValueError("Module mismatch")

            key = (module, rec["action_id"])

            if key in seen_ids:
                raise ValueError("Duplicate action ID")

            seen_ids.add(key)
            combined.append(rec)

    return combined


