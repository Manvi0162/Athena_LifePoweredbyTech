# Function 1: Normalize savings to a 30-day period
def normalize_savings_period(action):

    result = action.copy()

    amount = action.get("estimated_savings_mur")
    period = action.get("savings_period")

    result["normalized_savings_30d_mur"] = None
    result["normalization_status"] = "not_comparable"
    result["source_period_days"] = None

    if amount is None or not action.get("has_valid_savings"):
        return result

    value = Decimal(str(amount))

    if period == "month":
        days = 30

    elif isinstance(period, str) and " to " in period:
        try:
            start_text, end_text = period.split(" to ", 1)

            start = date.fromisoformat(start_text)
            end = date.fromisoformat(end_text)

            # Treat dates as [start, end)
            days = (end - start).days

            if days <= 0:
                return result

        except ValueError:
            return result

    else:
        return result

    normalized = (
        value * Decimal("30") / Decimal(days)
    ).quantize(
        Decimal("0.01"),
        rounding=ROUND_HALF_UP
    )

    result["normalized_savings_30d_mur"] = float(normalized)
    result["normalization_status"] = "normalized"
    result["source_period_days"] = days

    return result


