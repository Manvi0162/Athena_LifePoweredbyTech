from decimal import Decimal, InvalidOperation
from collections import defaultdict

def verify_household_data(data):
    issues = []
    verified_receipts = []
    possible_duplicates = []

    receipts = data["food"]["receipts"]
    items = data["food"]["receipt_items"]

    # Group items by receipt
    items_by_receipt = defaultdict(list)

    for item in items:
        items_by_receipt[item["receipt_id"]].append(item)

    # Check receipt totals
    for receipt in receipts:
        receipt_id = receipt["id"]
        receipt_items = items_by_receipt[receipt_id]

        try:
            expected = Decimal(str(receipt["total"]))
            calculated = sum(
                Decimal(str(item["line_total"]))
                for item in receipt_items
            )
        except (InvalidOperation, TypeError, KeyError):
            issues.append({
                "receipt_id": receipt_id,
                "issue": "Invalid or missing numerical value"
            })
            continue

        difference = abs(expected - calculated)

        if difference <= Decimal("0.05"):
            verified_receipts.append(receipt_id)
        else:
            issues.append({
                "receipt_id": receipt_id,
                "issue": "Receipt total mismatch",
                "expected": str(expected),
                "calculated": str(calculated),
                "difference": str(difference)
            })

    # Detect possible duplicate receipts
    seen = {}

    for receipt in receipts:
        key = (
            str(receipt.get("retailer", "")).strip().lower(),
            receipt.get("receipt_date"),
            str(receipt.get("total"))
        )

        if key in seen:
            possible_duplicates.append({
                "receipt_id": receipt["id"],
                "possible_duplicate_of": seen[key]
            })
        else:
            seen[key] = receipt["id"]

    return {
        "verified_receipts": verified_receipts,
        "issues": issues,
        "possible_duplicates": possible_duplicates,
        "water_status": (
            "available" if data["water"]["bills"]
            or data["water"]["readings"]
            else "insufficient_data"
        ),
        "electricity_status": (
            "available" if data["electricity"]["bills"]
            or data["electricity"]["readings"]
            else "insufficient_data"
        )
    }

