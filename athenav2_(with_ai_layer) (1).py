def normalize_module_summary(summary):

    module = summary.get("module")

    if module not in {"water", "electricity", "food"}:
        raise ValueError("Unknown module")

    forecast = summary.get("forecast")
    if not isinstance(forecast, dict):
        forecast = {}

    raw_cost = forecast.get("cost_rs")

    cost = None
    if raw_cost is not None and not isinstance(raw_cost, bool):
        try:
            value = Decimal(str(raw_cost))
            if value.is_finite() and value >= 0:
                cost = float(value)
        except (InvalidOperation, TypeError, ValueError):
            pass

    recommendations = []

    for rec in summary.get("recommendations", []):
        if not isinstance(rec, dict):
            continue

        saving = rec.get("saving")
        saving = saving if isinstance(saving, dict) else {}

        recommendations.append({
            "module": module,
            "action_id": rec.get("id"),
            "title": rec.get("title"),
            "kind": rec.get("kind"),
            "detail": rec.get("detail"),
            "saving": saving,
            "status": rec.get("status"),
            "evidence": rec.get("evidence", {})
        })

    return {
        "module": module,
        "status": (
            "data_available"
            if cost is not None
            else "insufficient_data"
        ),
        "original_status": summary.get("status"),
        "forecast_cost_mur": cost,
        "period_start": summary.get("period_start"),
        "period_end": summary.get("period_end"),
        "recommendations": recommendations,
        "recommendation_count": len(recommendations)
    }

