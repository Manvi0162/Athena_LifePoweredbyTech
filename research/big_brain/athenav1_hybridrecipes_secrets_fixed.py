def gemini_generate(prompt, json_output=True):
    errors = []
    for model in MODEL_CANDIDATES:
        for attempt in range(2):
            try:
                config = types.GenerateContentConfig(
                    response_mime_type='application/json' if json_output else 'text/plain',
                    temperature=0.2
                )
                response = client.models.generate_content(
                    model=model, contents=prompt, config=config
                )
                if not response.text:
                    raise ValueError('Gemini returned empty text')
                print('Gemini model used:', model)
                return response.text
            except Exception as exc:
                message = str(exc)
                errors.append(f'{model}: {message[:140]}')
                transient = any(code in message for code in (
                    '503', 'UNAVAILABLE', '429', 'RESOURCE_EXHAUSTED',
                    '500', 'INTERNAL', 'DEADLINE_EXCEEDED', '504'
                ))
                # Move on if a model is inaccessible; do not retry invalid prompts or auth failures.
                inaccessible = any(code in message for code in ('404', 'NOT_FOUND'))
                if transient and attempt == 0:
                    time.sleep(2 + random.random())
                    continue
                if transient or inaccessible:
                    break
                raise
    raise RuntimeError('No Gemini model available. ' + ' | '.join(errors))

