def rank_actions(actions):

    ranked = []

    for action in actions:
        score = (
            0.40 * action["impact"]
            + 0.35 * action["urgency"]
            + 0.25 * action["confidence"]
        )

        ranked.append({
            **action,
            "priority_score": round(score, 2)
        })

    return sorted(
        ranked,
        key=lambda x: (
            -x["priority_score"],
            x["id"]
        )
    )


